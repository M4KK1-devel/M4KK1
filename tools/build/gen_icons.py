#!/usr/bin/env python3
"""
M4KK1 4P1 - gen_icons.py
Description: PNG icon assets -> 32x32 RGBA C array source (icons_data.c/h).

Reads the icon source tree (apps/, folder/, net/), resizes every PNG to
32x32 RGBA (LANCZOS), and emits:
    usr/src/lib/icons_data.c  - const uint32_t arrays + name lookup table
    usr/src/lib/icons_data.h  - externs + lookup prototype

Run from repo root (or pass paths):  python tools/build/gen_icons.py
"""

import os
import sys
from PIL import Image

ICON_SRC = r"F:/Source/icons/sources"
OUT_C = "usr/src/lib/icons_data.c"
OUT_H = "usr/src/lib/icons_data.h"
SIZE = 32

# source file -> (C identifier, logical lookup name)
MAPPING = [
    ("apps/altr.png",            "icon_apps_altr",      "altr"),
    ("apps/backup-machine.png",  "icon_apps_backup",    "backup"),
    ("apps/clock.png",           "icon_apps_clock",     "clock"),
    ("apps/info.png",            "icon_apps_info",      "info"),
    ("apps/logview.png",         "icon_apps_logview",   "logview"),
    ("folder/folder.png",        "icon_dir",            "dir"),
    ("folder/folder-config.png", "icon_dir_config",     "dir_config"),
    ("folder/folder-desktop.png","icon_dir_desktop",    "dir_desktop"),
    ("folder/folder-documents.png","icon_dir_documents","dir_documents"),
    ("folder/folder-download.png","icon_dir_downloads", "dir_downloads"),
    ("folder/folder-home.png",   "icon_dir_home",       "dir_home"),
    ("folder/folder-music.png",  "icon_dir_music",      "dir_music"),
    ("net/054.png",              "icon_net_054",        "net_054"),
    ("net/055.png",              "icon_net_055",        "net_055"),
    ("net/056.png",              "icon_net_056",        "net_056"),
    ("net/057.png",              "icon_net_057",        "net_057"),
    ("net/058.png",              "icon_net_058",        "net_058"),
    ("net/059.png",              "icon_net_059",        "net_059"),
    ("net/060.png",              "icon_net_060",        "net_060"),
    ("net/061.png",              "icon_net_061",        "net_061"),
]

HEADER = """/*
 * M4KK1 4P1 - icons_data.c  [GENERATED - do not edit by hand]
 * Description: 32x32 ARGB icon bitmaps converted from PNG assets.
 *
 * Generated by tools/build/gen_icons.py. Each icon is a
 * const uint32_t[32*32] array in 0xAARRGGBB (alpha 0 = transparent).
 *
 * Copyright (c) 2026 Yaku Makki
 * SPDX-License-Identifier: 4P1-Custom
 */

#include "icons_data.h"

"""

H_HEADER = """/*
 * M4KK1 4P1 - icons_data.h  [GENERATED - do not edit by hand]
 * Description: externs for the PNG-converted icon bitmap set.
 *
 * Copyright (c) 2026 Yaku Makki
 * SPDX-License-Identifier: 4P1-Custom
 */

#ifndef ICONS_DATA_H
#define ICONS_DATA_H

#define ICON_DATA_SIZE 32

#include <stdint.h>

"""


def convert(path):
    im = Image.open(path)
    if im.mode != "RGBA":
        im = im.convert("RGBA")
    if im.size != (SIZE, SIZE):
        im = im.resize((SIZE, SIZE), Image.LANCZOS)
    px = im.load()
    out = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = px[x, y]
            out.append((a << 24) | (r << 16) | (g << 8) | b)
    return out


def main():
    rows = []
    for rel, ident, logical in MAPPING:
        src = os.path.join(ICON_SRC, rel.replace("/", os.sep))
        if not os.path.exists(src):
            print("MISSING:", src)
            sys.exit(1)
        pixels = convert(src)
        rows.append((ident, logical, pixels))

    with open(OUT_C, "w", newline="\n") as f:
        f.write(HEADER)
        for ident, _, pixels in rows:
            f.write("uint32_t %s[ICON_DATA_SIZE * ICON_DATA_SIZE] = {\n" % ident)
            for y in range(SIZE):
                vals = ", ".join("0x%08X" % p for p in pixels[y * SIZE:(y + 1) * SIZE])
                f.write("    %s%s\n" % (vals, "," if y < SIZE - 1 else ""))
            f.write("};\n\n")
        f.write("/* Logical-name lookup table (NULL name terminates). */\n")
        f.write("struct icon_data_entry icon_data_table[] = {\n")
        for ident, logical, _ in rows:
            f.write('    { "%s", %s },\n' % (logical, ident))
        f.write("    { (char *)0, (uint32_t *)0 }\n")
        f.write("};\n\n")
        f.write("static int idata_eq(const char *a, const char *b)\n{\n")
        f.write("    while (*a && *a == *b) { a++; b++; }\n")
        f.write("    return *a == *b;\n}\n\n")
        f.write("uint32_t *icons_data_find(const char *name)\n{\n")
        f.write("    if (!name)\n        return (uint32_t *)0;\n")
        f.write("    for (int i = 0; icon_data_table[i].name; i++)\n")
        f.write("        if (idata_eq(icon_data_table[i].name, name))\n")
        f.write("            return icon_data_table[i].pixels;\n")
        f.write("    return (uint32_t *)0;\n}\n")

    with open(OUT_H, "w", newline="\n") as f:
        f.write(H_HEADER)
        for ident, _, _ in rows:
            f.write("extern uint32_t %s[ICON_DATA_SIZE * ICON_DATA_SIZE];\n" % ident)
        f.write("""
struct icon_data_entry {
    char *name;
    uint32_t *pixels;
};

extern struct icon_data_entry icon_data_table[];

/*
 * icons_data_find - Look up an icon bitmap by logical name
 * ("dir", "dir_home", "clock", "net_054", ...).
 *
 * Return: pointer to 32x32 ARGB pixels, NULL if unknown name.
 */
uint32_t *icons_data_find(const char *name);

#endif /* ICONS_DATA_H */
""")

    total = sum(1 for _ in rows)
    print("generated %s / %s with %d icons" % (OUT_C, OUT_H, total))


if __name__ == "__main__":
    main()
