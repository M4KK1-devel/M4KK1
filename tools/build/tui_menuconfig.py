#!/usr/bin/env python3
"""M4KK1 4P1 - tui_menuconfig.py
ncurses (python curses) build-configuration TUI.

Replaces the whiptail/dialog/bashmenu stack: the WSL build host has
neither whiptail nor dialog installed, so the old script always fell
back to the plain numbered bash menu.  This is a single-dependency
ncurses TUI (python3 + curses, both in the base image).

Writes the exact same build.config format that build_krn.sh sources.

Keys:  Up/Down move · Enter select · Space toggle · Esc back ·
       q cancel dialog · Tab switch
"""
import curses
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
CONFIG = os.path.join(ROOT, "build.config")

MODES = [
    ("full",      "Full desktop (graphics + Copland + Sprach + PCC)"),
    ("full-test", "Full desktop + autologin + serial test shell"),
    ("cmd-only",  "Command-line system (no graphics)"),
    ("minimal",   "Minimal kernel (boot banner + halt)"),
    ("recovery",  "cmd-only + fsck / reset-passwd tools"),
]

TESTS = [
    ("TEST_SMOKE",    "smoke", "Boot smoke test (serial, no panic)"),
    ("TEST_GRAPHICS", "gfx",   "Graphics bring-up (desktop visible)"),
    ("TEST_DRAG",     "drag",  "Window drag repro (QEMU HMP)"),
    ("TEST_RMENU",    "rmenu", "Right-click context menu repro"),
    ("TEST_PCC",      "pcc",   "PCC self-host compile check"),
]

VGAS = [
    ("std",    "Standard VGA (default, VESA)"),
    ("cirrus", "Cirrus Logic GD5446"),
    ("virtio", "virtio-gpu"),
]

CFG_ORDER = ["BUILD_MODE", "OUTPUT_DIR", "QEMU_MEMORY", "QEMU_VGA",
             "TEST_SMOKE", "TEST_GRAPHICS", "TEST_DRAG",
             "TEST_RMENU", "TEST_PCC", "MAKE_JOBS"]


def load_cfg():
    cfg = {
        "BUILD_MODE": "full", "OUTPUT_DIR": "output",
        "QEMU_MEMORY": "512", "QEMU_VGA": "std",
        "TEST_SMOKE": "yes", "TEST_GRAPHICS": "yes",
        "TEST_DRAG": "no", "TEST_RMENU": "no", "TEST_PCC": "yes",
        "MAKE_JOBS": str(os.cpu_count() or 4),
    }
    try:
        with open(CONFIG) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip().strip('"')
                if k in cfg:
                    cfg[k] = v
    except FileNotFoundError:
        pass
    return cfg


def save_cfg(cfg):
    with open(CONFIG, "w") as f:
        f.write("# M4KK1 build configuration — generated by "
                "menuconfig\n")
        f.write("# (sourced by tools/build/build_krn.sh; edit "
                "manually if you prefer)\n")
        for k in CFG_ORDER:
            f.write('%s="%s"\n' % (k, cfg[k]))


# ══════════════ low-level drawing helpers ══════════════

def draw_frame(scr, title, h=None, w=None):
    """Centered frame; returns the content window (derived)."""
    my, mx = scr.getmaxyx()
    h = h or min(my - 2, 24)
    w = w or min(mx - 4, 74)
    if h < 8 or w < 30:
        raise RuntimeError("terminal too small")
    y0 = (my - h) // 2
    x0 = (mx - w) // 2
    win = curses.newwin(h, w, y0, x0)
    win.erase()
    win.box()
    t = " %s " % title
    win.addstr(0, max(1, (w - len(t)) // 2), t[:w - 2],
               curses.A_BOLD | curses.color_pair(2))
    return win


def draw_status(win, text, w):
    win.addstr(win.getmaxyx()[0] - 2, 2, (" " + text)[:w - 4],
               curses.color_pair(3))


# ══════════════ widgets ══════════════

def w_menu(scr, title, hint, items, sel=0):
    """items: list of (tag, desc). Returns index, or None on Esc/q."""
    h = min(len(items) * 2 + 7, curses.LINES - 2)
    w = min(max(len(title) + 4,
                max(len(t) + len(d) + 8 for t, d in items) + 4) + 4,
            curses.COLS - 2)
    win = draw_frame(scr, title, h, w)
    off = 1
    while True:
        for i, (tag, desc) in enumerate(items):
            attr = (curses.A_REVERSE if i == sel else
                    curses.color_pair(1))
            row = off + i * 1
            if row < h - 3:
                line = " %-18s %s" % (tag, desc)
                win.addstr(row, 1, line[:w - 2], attr)
        win.clrtobot()
        win.box()
        draw_status(win, hint, w)
        win.refresh()
        k = win.getch()
        if k in (curses.KEY_UP, ord('k')):
            sel = (sel - 1) % len(items)
        elif k in (curses.KEY_DOWN, ord('j')):
            sel = (sel + 1) % len(items)
        elif k in (curses.KEY_ENTER, 10, 13):
            return sel
        elif k in (27, ord('q')):
            return None


def w_checklist(scr, title, hint, items, checked):
    """items: list of (tag, desc). checked: set of tags.
    Returns the new set, or None on Esc/q (no change)."""
    sel = 0
    picked = set(checked)
    while True:
        h = min(len(items) * 2 + 7, curses.LINES - 2)
        w = min(max(len(title) + 4,
                    max(len(t) + len(d) + 10 for t, d in items) + 4)
                + 4, curses.COLS - 2)
        win = draw_frame(scr, title, h, w)
        for i, (tag, desc) in enumerate(items):
            mark = "[x]" if tag in picked else "[ ]"
            attr = (curses.A_REVERSE if i == sel else
                    curses.color_pair(1))
            win.addstr(1 + i, 1,
                       " %s %-14s %s" % (mark, tag, desc)[:w - 2], attr)
        win.box()
        draw_status(win, hint, w)
        win.refresh()
        k = win.getch()
        if k in (curses.KEY_UP, ord('k')):
            sel = (sel - 1) % len(items)
        elif k in (curses.KEY_DOWN, ord('j')):
            sel = (sel + 1) % len(items)
        elif k == ord(' '):
            tag = items[sel][0]
            picked.symmetric_difference_update({tag})
        elif k in (curses.KEY_ENTER, 10, 13):
            return picked
        elif k in (27, ord('q')):
            return None


def w_input(scr, title, prompt, default):
    """Single-line input. Returns string, or None on Esc."""
    win = draw_frame(scr, title, 8, max(58, len(prompt) + 8))
    win.addstr(2, 2, prompt[:win.getmaxyx()[1] - 4])
    curses.echo()
    curses.curs_set(1)
    box = win.subwin(3, win.getmaxyx()[1] - 6,
                     win.getbegyx()[0] + 4, win.getbegyx()[1] + 3)
    box.erase()
    box.border()
    curses.noecho()
    curses.curs_set(0)
    # manual line editor (echo() inside subwin is awkward on some
    # termcaps; read char by char instead)
    buf = list(default)
    cur = len(buf)
    while True:
        shown = "".join(buf)[-box.getmaxyx()[1] - 4:]
        box.addstr(1, 1, shown.ljust(box.getmaxyx()[1] - 2))
        box.border()
        win.refresh()
        k = box.getch()
        if k in (curses.KEY_ENTER, 10, 13):
            return "".join(buf)
        if k in (27, ord('q') and not buf):
            return None
        if k in (curses.KEY_BACKSPACE, 8, 127):
            if cur > 0:
                cur -= 1
                buf.pop(cur)
        elif 32 <= k < 127 and len(buf) < 60:
            buf.insert(cur, chr(k))
            cur += 1


# ══════════════ main menu ══════════════

def summary_lines(cfg):
    tests = " ".join("%s=%s" % (t[1], "y" if cfg[t[0]] == "yes"
                                else "n") for t in TESTS)
    return [
        "Mode:      %s" % cfg["BUILD_MODE"],
        "Output:    %s" % cfg["OUTPUT_DIR"],
        "QEMU:      %sMB / %s" % (cfg["QEMU_MEMORY"], cfg["QEMU_VGA"]),
        "Tests:     %s" % tests,
        "Jobs:      %s" % cfg["MAKE_JOBS"],
    ]


def main(scr):
    curses.curs_set(0)
    curses.start_color()
    curses.use_default_colors()
    curses.init_pair(1, curses.COLOR_WHITE, -1)
    curses.init_pair(2, curses.COLOR_CYAN, -1)
    curses.init_pair(3, curses.COLOR_YELLOW, -1)
    curses.init_pair(4, curses.COLOR_GREEN, -1)

    cfg = load_cfg()
    items = [
        ("Build mode",      "choose the build profile"),
        ("Output directory", "where ISO artifacts land"),
        ("QEMU memory",     "guest RAM in MB"),
        ("QEMU VGA",        "emulated video card"),
        ("Test selection",  "toggle post-build regression tests"),
        ("Save & exit",     "write build.config"),
        ("Discard & exit",  "quit without saving"),
    ]
    sel = 0
    while True:
        h = min(len(items) + len(summary_lines(cfg)) + 8,
                curses.LINES - 2)
        w = min(70, curses.COLS - 2)
        win = draw_frame(scr, "M4KK1 Build Configuration", h, w)
        row = 1
        for ln in summary_lines(cfg):
            win.addstr(row, 2, ln[:w - 4], curses.color_pair(4))
            row += 1
        row += 1
        for i, (tag, desc) in enumerate(items):
            attr = curses.A_REVERSE if i == sel else curses.color_pair(1)
            win.addstr(row + i, 2,
                       " %-20s %s" % (tag, desc)[:w - 4], attr)
        win.box()
        draw_status(win,
                    "↑↓ move · Enter select · Esc/q back · s saves",
                    w)
        win.refresh()
        k = win.getch()
        if k in (curses.KEY_UP, ord('k')):
            sel = (sel - 1) % len(items)
        elif k in (curses.KEY_DOWN, ord('j')):
            sel = (sel + 1) % len(items)
        elif k == ord('s'):
            save_cfg(cfg)
            return 0
        elif k in (curses.KEY_ENTER, 10, 13):
            if sel == 0:
                idx = w_menu(scr, "Build mode",
                             "Enter choose · Esc back", MODES,
                             [m[0] for m in MODES].index(
                                 cfg["BUILD_MODE"])
                             if cfg["BUILD_MODE"] in
                             [m[0] for m in MODES] else 0)
                if idx is not None:
                    cfg["BUILD_MODE"] = MODES[idx][0]
            elif sel == 1:
                v = w_input(scr, "Output directory",
                            "Directory for ISO artifacts",
                            cfg["OUTPUT_DIR"])
                if v is not None and v.strip():
                    cfg["OUTPUT_DIR"] = v.strip()
            elif sel == 2:
                v = w_input(scr, "QEMU memory",
                            "Guest RAM in MB", cfg["QEMU_MEMORY"])
                if v is not None and v.strip().isdigit():
                    cfg["QEMU_MEMORY"] = v.strip()
            elif sel == 3:
                idx = w_menu(scr, "QEMU VGA", "Enter choose · Esc back",
                             VGAS,
                             [g[0] for g in VGAS].index(
                                 cfg["QEMU_VGA"])
                             if cfg["QEMU_VGA"] in
                             [g[0] for g in VGAS] else 0)
                if idx is not None:
                    cfg["QEMU_VGA"] = VGAS[idx][0]
            elif sel == 4:
                picked = w_checklist(scr, "Test selection",
                                     "Space toggle · Enter accept · "
                                     "Esc back",
                                     [(t[1], t[2]) for t in TESTS],
                                     {t[1] for t in TESTS
                                      if cfg[t[0]] == "yes"})
                if picked is not None:
                    for key, tag, _ in TESTS:
                        cfg[key] = "yes" if tag in picked else "no"
            elif sel == 5:
                save_cfg(cfg)
                return 0
            elif sel == 6:
                return 1
        elif k in (27, ord('q')):
            return 1


def run():
    os.environ.setdefault("ESCDELAY", "25")
    try:
        return curses.wrapper(main)
    except RuntimeError as e:
        print("menuconfig: %s (need >= 34x26 terminal)" % e,
              file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(run())
