#include <ncurses.h>
#include <stdlib.h>
#include <string.h>
#include <stdio.h>
#include <time.h>

#define VAL_MAX 64
#define NITEMS 7

/* ── config state ── */
struct cfg {
	char mode[VAL_MAX];
	char outdir[VAL_MAX];
	char mem[VAL_MAX];
	char vga[VAL_MAX];
	int  t_smoke, t_gfx, t_drag, t_rmenu, t_pcc;
	char jobs[VAL_MAX];
};

static struct cfg C = {
	"full", "output", "512", "std",
	1, 1, 0, 0, 1, "4",
};

static const char *MODES[] = {
	"full", "full-test", "cmd-only", "minimal", "recovery",
};
#define NMODES ((int)(sizeof(MODES) / sizeof(MODES[0])))

static const char *mode_desc(const char *m)
{
	if (!strcmp(m, "full"))      return "Full desktop (graphics + Copland + Sprach + PCC)";
	if (!strcmp(m, "full-test")) return "Full desktop + autologin + serial test shell";
	if (!strcmp(m, "cmd-only"))  return "Command-line system (no graphics)";
	if (!strcmp(m, "minimal"))   return "Minimal kernel (boot banner + halt)";
	if (!strcmp(m, "recovery"))  return "cmd-only + fsck / reset-passwd tools";
	return "?";
}

/* ── build.config I/O (shell-sourceable format) ── */
static void trim(char *s)
{
	size_t n = strlen(s);
	while (n && (s[n-1]=='\n' || s[n-1]=='\r' || s[n-1]==' ')) s[--n] = 0;
}

static void load_cfg(const char *path)
{
	FILE *f = fopen(path, "r");
	char line[256];
	if (!f) return;
	while (fgets(line, sizeof(line), f)) {
		char key[VAL_MAX], val[VAL_MAX];
		char *eq = strchr(line, '=');
		if (!eq) continue;
		*eq = 0;
		snprintf(key, sizeof(key), "%.63s", line);
		snprintf(val, sizeof(val), "%.63s", eq + 1);
		trim(key); trim(val);
		/* strip quotes */
		size_t v = strlen(val);
		if (v >= 2 && val[0]=='"' && val[v-1]=='"') { val[v-1]=0; memmove(val, val+1, v); }
		if      (!strcmp(key, "BUILD_MODE"))    snprintf(C.mode,   VAL_MAX, "%s", val);
		else if (!strcmp(key, "OUTPUT_DIR"))    snprintf(C.outdir, VAL_MAX, "%s", val);
		else if (!strcmp(key, "QEMU_MEMORY"))   snprintf(C.mem,    VAL_MAX, "%s", val);
		else if (!strcmp(key, "QEMU_VGA"))      snprintf(C.vga,    VAL_MAX, "%s", val);
		else if (!strcmp(key, "TEST_SMOKE"))    C.t_smoke = val[0]=='y';
		else if (!strcmp(key, "TEST_GRAPHICS")) C.t_gfx   = val[0]=='y';
		else if (!strcmp(key, "TEST_DRAG"))     C.t_drag  = val[0]=='y';
		else if (!strcmp(key, "TEST_RMENU"))    C.t_rmenu = val[0]=='y';
		else if (!strcmp(key, "TEST_PCC"))      C.t_pcc   = val[0]=='y';
		else if (!strcmp(key, "MAKE_JOBS"))     snprintf(C.jobs,   VAL_MAX, "%s", val);
	}
	fclose(f);
}

static int save_cfg(const char *path)
{
	FILE *f = fopen(path, "w");
	if (!f) return -1;
	fprintf(f, "# M4KK1 build configuration — generated by menuconfig\n");
	fprintf(f, "# (sourced by tools/build/build_krn.sh; edit manually if you prefer)\n");
	fprintf(f, "BUILD_MODE=\"%s\"\n",   C.mode);
	fprintf(f, "OUTPUT_DIR=\"%s\"\n",   C.outdir);
	fprintf(f, "QEMU_MEMORY=\"%s\"\n",  C.mem);
	fprintf(f, "QEMU_VGA=\"%s\"\n",     C.vga);
	fprintf(f, "TEST_SMOKE=\"%s\"\n",   C.t_smoke ? "yes" : "no");
	fprintf(f, "TEST_GRAPHICS=\"%s\"\n", C.t_gfx  ? "yes" : "no");
	fprintf(f, "TEST_DRAG=\"%s\"\n",    C.t_drag ? "yes" : "no");
	fprintf(f, "TEST_RMENU=\"%s\"\n",   C.t_rmenu ? "yes" : "no");
	fprintf(f, "TEST_PCC=\"%s\"\n",     C.t_pcc ? "yes" : "no");
	fprintf(f, "MAKE_JOBS=\"%s\"\n",    C.jobs);
	fclose(f);
	return 0;
}

/* ── small frame helper: boxed window with a title ── */
static WINDOW *boxed(int h, int w, const char *title)
{
	int y0 = (LINES - h) / 2, x0 = (COLS - w) / 2;
	if (y0 < 0) y0 = 0;
	if (x0 < 0) x0 = 0;
	WINDOW *win = newwin(h, w, y0, x0);
	box(win, 0, 0);
	wattron(win, A_BOLD | COLOR_PAIR(2));
	mvwaddnstr(win, 0, 2, title, w - 4);
	wattroff(win, A_BOLD | COLOR_PAIR(2));
	keypad(win, TRUE);
	return win;
}

/* ── radio menu dialog; returns selected index or -1 on Esc ── */
static int dlg_menu(const char *title, const char *hint,
		    const char **labels, const char **descs,
		    int n, int cur)
{
	int h = n + 5, w = 70;
	if (h > LINES - 2) h = LINES - 2;
	WINDOW *win = boxed(h, w, title);
	int sel = cur;
	while (1) {
		for (int i = 0; i < n; i++) {
			int attr = (i == sel) ? A_REVERSE : COLOR_PAIR(1);
			char row[128];
			snprintf(row, sizeof(row), " %-12s %s",
				 labels[i], descs[i] ? descs[i] : "");
			wattron(win, attr);
			mvwaddnstr(win, 2 + i, 1, row, w - 3);
			wattroff(win, attr);
		}
		wattron(win, COLOR_PAIR(3));
		mvwaddnstr(win, h - 2, 1, hint, w - 3);
		wattroff(win, COLOR_PAIR(3));
		wrefresh(win);
		int k = wgetch(win);
		if (k == KEY_UP || k == 'k')   sel = (sel + n - 1) % n;
		else if (k == KEY_DOWN || k == 'j') sel = (sel + 1) % n;
		else if (k == '\n' || k == '\r' || k == KEY_ENTER) { delwin(win); return sel; }
		else if (k == 27) { delwin(win); return -1; }
	}
}

/* ── input dialog; returns 0 on Enter (buf updated), -1 on Esc ── */
static int dlg_input(const char *title, const char *prompt,
		     char *buf, int bufsz)
{
	WINDOW *win = boxed(7, 58, title);
	echo(); curs_set(1);
	mvwaddnstr(win, 2, 2, prompt, 54);
	mvwaddnstr(win, 4, 2, "> ", 56);
	wmove(win, 4, 4);
	wattron(win, COLOR_PAIR(1));
	int r = wgetnstr(win, buf, bufsz - 1);
	wattroff(win, COLOR_PAIR(1));
	noecho(); curs_set(0);
	delwin(win);
	if (r == ERR || (buf[0] == 0)) return -1;
	return 0;
}

/* ── checklist dialog; toggles flags in-place, Enter=done, Esc=cancel ── */
static void dlg_tests(void)
{
	const char *labels[5] = { "smoke", "gfx", "drag", "rmenu", "pcc" };
	const char *descs[5] = {
		"Boot smoke test (serial, no panic)",
		"Graphics bring-up (desktop visible)",
		"Window drag repro (QEMU HMP)",
		"Right-click context menu repro",
		"PCC self-host compile check",
	};
	int vals[5] = { C.t_smoke, C.t_gfx, C.t_drag, C.t_rmenu, C.t_pcc };
	int sel = 0;
	WINDOW *win = boxed(11, 70, "Test selection");
	while (1) {
		for (int i = 0; i < 5; i++) {
			int attr = (i == sel) ? A_REVERSE : COLOR_PAIR(1);
			char row[96];
			snprintf(row, sizeof(row), " [%c] %-8s %s",
				 vals[i] ? 'x' : ' ', labels[i], descs[i]);
			wattron(win, attr);
			mvwaddnstr(win, 2 + i, 1, row, 67);
			wattroff(win, attr);
		}
		wattron(win, COLOR_PAIR(3));
		mvwaddnstr(win, 8, 1, "space toggle · Enter accept · Esc cancel", 67);
		wattroff(win, COLOR_PAIR(3));
		wrefresh(win);
		int k = wgetch(win);
		if (k == KEY_UP || k == 'k')   sel = (sel + 4) % 5;
		else if (k == KEY_DOWN || k == 'j') sel = (sel + 1) % 5;
		else if (k == ' ') vals[sel] = !vals[sel];
		else if (k == '\n' || k == '\r' || k == KEY_ENTER) {
			C.t_smoke = vals[0]; C.t_gfx = vals[1];
			C.t_drag = vals[2];  C.t_rmenu = vals[3];
			C.t_pcc = vals[4];
			break;
		} else if (k == 27) break;
	}
	delwin(win);
}

int main(void)
{
	initscr();
	if (has_colors()) {
		start_color();
		use_default_colors();
		init_pair(1, COLOR_WHITE, -1);
		init_pair(2, COLOR_CYAN, -1);
		init_pair(3, COLOR_YELLOW, -1);
		init_pair(4, COLOR_GREEN, -1);
	}
	curs_set(0);
	keypad(stdscr, TRUE);
	noecho();

	const char *path = "build.config";
	load_cfg(path);

	const char *items[NITEMS] = {
		"Build mode", "Output directory", "QEMU memory",
		"QEMU VGA", "Test selection",
		"Save & exit", "Discard & exit",
	};
	int sel = 0;

	while (1) {
		/* summary block */
		char sum[6][80];
		snprintf(sum[0], 80, " Mode:      %s", C.mode);
		snprintf(sum[1], 80, " Output:    %s", C.outdir);
		snprintf(sum[2], 80, " QEMU: %.16sMB / %.8s  Jobs: %.4s",
			 C.mem, C.vga, C.jobs);
		snprintf(sum[3], 80, " Tests:     smoke=%c gfx=%c drag=%c rmenu=%c pcc=%c",
			 C.t_smoke?'y':'n', C.t_gfx?'y':'n',
			 C.t_drag?'y':'n', C.t_rmenu?'y':'n', C.t_pcc?'y':'n');
		int h = NITEMS + 4 + 6 + 2, w = 72;
		if (h > LINES - 1) h = LINES - 1;
		if (w > COLS - 1)  w = COLS - 1;
		WINDOW *win = boxed(h, w, "M4KK1 Build Configuration");
		int row = 1;
		for (int i = 0; i < 4; i++) {
			wattron(win, COLOR_PAIR(4));
			mvwaddnstr(win, row++, 2, sum[i], w - 4);
			wattroff(win, COLOR_PAIR(4));
		}
		row++;
		for (int i = 0; i < NITEMS; i++) {
			int attr = (i == sel) ? A_REVERSE : COLOR_PAIR(1);
			const char *desc = "";
			if (i == 0) desc = "choose the build profile";
			else if (i == 1) desc = "where ISO artifacts land";
			else if (i == 2) desc = "guest RAM in MB";
			else if (i == 3) desc = "emulated video card";
			else if (i == 4) desc = "toggle post-build regression tests";
			else if (i == 5) desc = "write build.config";
			else desc = "quit without saving";
			char line[100];
			snprintf(line, sizeof(line), " %-18s %s", items[i], desc);
			wattron(win, attr);
			mvwaddnstr(win, row + i, 2, line, w - 4);
			wattroff(win, attr);
		}
		wattron(win, A_REVERSE | COLOR_PAIR(3));
		mvwaddnstr(win, h - 2, 2,
			   "j/k move · Enter select · s saves · q quits", w - 4);
		wattroff(win, A_REVERSE | COLOR_PAIR(3));
		wrefresh(win);

		int k = wgetch(win);
		delwin(win);
		if (k == KEY_UP || k == 'k')   sel = (sel + NITEMS - 1) % NITEMS;
		else if (k == KEY_DOWN || k == 'j') sel = (sel + 1) % NITEMS;
		else if (k == 's' || k == 'S') { save_cfg(path); break; }
		else if (k == 'q' || k == 27) break;
		else if (k == '\n' || k == '\r' || k == KEY_ENTER) {
			if (sel == 0) {
				int cur = 0;
				for (int i = 0; i < NMODES; i++)
					if (!strcmp(MODES[i], C.mode)) cur = i;
				const char *descs[NMODES];
				for (int i = 0; i < NMODES; i++)
					descs[i] = mode_desc(MODES[i]);
				int r = dlg_menu("Build mode",
						 "Enter choose · Esc back",
						 MODES, descs, NMODES, cur);
				if (r >= 0)
					snprintf(C.mode, VAL_MAX, "%s", MODES[r]);
				touchwin(stdscr); refresh();
			} else if (sel == 1) {
				char buf[VAL_MAX];
				snprintf(buf, VAL_MAX, "%s", C.outdir);
				if (dlg_input("Output directory",
					      "Directory for ISO artifacts",
					      buf, VAL_MAX) == 0)
					snprintf(C.outdir, VAL_MAX, "%s", buf);
				clear(); refresh();
			} else if (sel == 2) {
				char buf[VAL_MAX];
				snprintf(buf, VAL_MAX, "%s", C.mem);
				if (dlg_input("QEMU memory",
					      "Guest RAM in MB",
					      buf, VAL_MAX) == 0)
					snprintf(C.mem, VAL_MAX, "%s", buf);
				clear(); refresh();
			} else if (sel == 3) {
				const char *labels[3] = { "std", "cirrus", "virtio" };
				const char *descs[3] = {
					"Standard VGA (default, VESA)",
					"Cirrus Logic GD5446",
					"virtio-gpu",
				};
				int cur = 0;
				for (int i = 0; i < 3; i++)
					if (!strcmp(labels[i], C.vga)) cur = i;
				int r = dlg_menu("QEMU VGA",
						 "Enter choose · Esc back",
						 labels, descs, 3, cur);
				if (r >= 0)
					snprintf(C.vga, VAL_MAX, "%s", labels[r]);
				clear(); refresh();
			} else if (sel == 4) {
				dlg_tests();
				clear(); refresh();
			} else if (sel == 5) {
				save_cfg(path);
				break;
			} else if (sel == 6) {
				break;
			}
		}
	}

	endwin();
	return 0;
}
