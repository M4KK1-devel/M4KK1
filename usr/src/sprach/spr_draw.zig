//! spr_draw.zig — hot-path pixel primitives for Sprach (M4KK1 4P1).
//!
//! C ABI out (consumed by sprach.c), freestanding i386, no lib Zig.
//! Each exported fn mirrors the exact semantics of the C original in
//! usr/src/sprach/sprach.c (sp_fill / sp_rect / sp_draw_char /
//! sp_draw_str / sp_draw_str_bold) — byte-identical output is the
//! acceptance bar (tools/build/zig_equivalence_test.py compares pixel
//! buffers between the C and Zig implementations).
//!
//! Zig 规范 v1.0 见 docs/zig-standard.md。

