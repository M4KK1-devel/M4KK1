// ─── primitives ────────────────────────────────────────────────

/// sp_fill equivalent: bulk fill n dwords (rep stosd in the C build).
export fn zsp_fill(buf: PixBuf, n: i32, c: u32) void {
    if (n <= 0) return;
    @memset(buf[0..@intCast(n)], c);
}

/// sp_rect equivalent: clipped rect fill.  (bw,bh) is the buffer's
/// TRUE geometry — never SCREEN_W/SCREEN_H (see sprach.c comment).
export fn zsp_rect(buf: PixBuf, bw: i32, bh: i32, x: i32, y: i32,
                   rw: i32, rh: i32, c: u32) void {
    if (bw <= 0 or bh <= 0) return;
    const x0 = @max(x, 0);
    const y0 = @max(y, 0);
    const x1 = @min(x +% rw, bw);
    const y1 = @min(y +% rh, bh);
    if (x0 >= x1 or y0 >= y1) return;

    const stride: usize = @intCast(bw);
    const fx0: usize = @intCast(x0);
    const w: usize = @intCast(x1 - x0);
    var py: usize = @intCast(y0);
    const end: usize = @intCast(y1);
    while (py < end) : (py += 1) {
        const base = py * stride + fx0;
        @memset(buf[base .. base + w], c);
    }
}

/// sp_px equivalent: bounds-checked single pixel store.
export fn zsp_px(buf: PixBuf, bw: i32, bh: i32, x: i32, y: i32, c: u32) void {
    if (x < 0 or x >= bw or y < 0 or y >= bh) return;
    const idx = @as(usize, @intCast(y)) * @as(usize, @intCast(bw)) +
        @as(usize, @intCast(x));
    buf[idx] = c;
}

/// sp_draw_char equivalent: one 5x7 font glyph (95 printable ASCII
/// 0x20..0x7E — table has 95 entries, NOT 96; keep in sync with the
/// historical C table layout, spec §4a).
export fn zsp_draw_char(buf: PixBuf, bw: i32, bh: i32, x: i32, y: i32,
                        ch: u8, fg: u32) void {
    if (ch < 0x20 or ch > 0x7E) return;
    const idx: usize = @as(usize, ch) - 0x20;
    var row: i32 = 0;
    while (row < 7) : (row += 1) {
        const bits: u8 = font5x7[idx * 7 + @as(usize, @intCast(row))];
        var col: i32 = 0;
        while (col < 5) : (col += 1) {
            if (bits & (@as(u8, 1) << @intCast(4 - col)) != 0)
                zsp_px(buf, bw, bh, x +% col, y +% row, fg);
        }
    }
}

/// sp_draw_str equivalent: NUL-terminated string, 6px advance.
export fn zsp_draw_str(buf: PixBuf, bw: i32, bh: i32, x: i32, y: i32,
                       s: [*:0]const u8, fg: u32) void {
    var cx = x;
    var i: usize = 0;
    while (s[i] != 0) : (i += 1) {
        zsp_draw_char(buf, bw, bh, cx, y, s[i], fg);
        cx +%= 6;
    }
}

/// sp_draw_char_bold equivalent: double-strike (1px right + 1px down).
export fn zsp_draw_char_bold(buf: PixBuf, bw: i32, bh: i32, x: i32, y: i32,
                             ch: u8, fg: u32) void {
    zsp_draw_char(buf, bw, bh, x, y, ch, fg);
    zsp_draw_char(buf, bw, bh, x +% 1, y, ch, fg);
    zsp_draw_char(buf, bw, bh, x, y +% 1, ch, fg);
}

/// sp_draw_str_bold equivalent: 7px advance bold string.
export fn zsp_draw_str_bold(buf: PixBuf, bw: i32, bh: i32, x: i32, y: i32,
                            s: [*:0]const u8, fg: u32) void {
    var cx = x;
    var i: usize = 0;
    while (s[i] != 0) : (i += 1) {
        zsp_draw_char_bold(buf, bw, bh, cx, y, s[i], fg);
        cx +%= 7;
    }
}

// ─── self-test (zig test / native; run on build host) ──────────
// Tests below avoid zsp_draw_char (needs the C-side font table);
// they cover fill/rect/px clipping paths.  Glyph rendering is
// covered by tools/build/zig_equivalence_test.py against the real
// sprach.c table.

test "zsp_fill basic" {
    var buf: [64]u32 = undefined;
    @memset(&buf, 0);
    zsp_fill(&buf, 16, 0xAABBCCDD);
    try std.testing.expectEqual(@as(u32, 0xAABBCCDD), buf[15]);
    try std.testing.expectEqual(@as(u32, 0), buf[16]);
}

test "zsp_rect clip + fill" {
    var buf: [20 * 10]u32 = undefined;
    @memset(&buf, 0);
    // rect partially off the left/top: only in-bounds part painted
    zsp_rect(&buf, 20, 10, -5, -2, 10, 5, 0xFF);
    var count: usize = 0;
    for (buf) |p| {
        if (p == 0xFF) count += 1;
    }
    // visible part: x in [0,5), y in [0,3) = 15 px
    try std.testing.expectEqual(@as(usize, 15), count);
}

test "zsp_draw_char bounds" {
    var buf: [100]u32 = undefined;
    @memset(&buf, 0);
    // non-printable chars return BEFORE touching font5x7 — safe to
    // test even with an unresolved extern table (no table access).
    zsp_draw_char(&buf, 10, 10, 0, 0, '\n', 0xFF);
    zsp_draw_char(&buf, 10, 10, 0, 0, 0x7F, 0xFF);
    var any: u32 = 0;
    for (buf) |p| any |= p;
    try std.testing.expectEqual(@as(u32, 0), any);
}
